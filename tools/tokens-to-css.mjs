#!/usr/bin/env node
// Turns a DTCG design-system token folder into a theme's CSS variables.
//
//   node tools/tokens-to-css.mjs <tokens-dir> <out.css> [--name kiln]
//
// <tokens-dir> holds primitive.tokens.json, semantic.tokens.json (light / default values),
// optional component.tokens.json and modes/<mode>.tokens.json (overrides per mode).
// Every token becomes a CSS variable: color.surface.page -> --color-surface-page.
// Light values go on :root; each other mode goes on :root[data-theme="<mode>"].
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, basename } from "node:path";

const [dir, out, ...rest] = process.argv.slice(2);
if (!dir || !out) {
  console.error("usage: tokens-to-css.mjs <tokens-dir> <out.css> [--name <theme>]");
  process.exit(1);
}
const name = rest[rest.indexOf("--name") + 1] || basename(dir);

const load = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : {});

function flatten(obj, prefix = [], acc = {}) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) acc[[...prefix, k].join(".")] = v.$value;
    else if (v && typeof v === "object") flatten(v, [...prefix, k], acc);
  }
  return acc;
}

const base = {
  ...flatten(load(join(dir, "primitive.tokens.json"))),
  ...flatten(load(join(dir, "semantic.tokens.json"))),
  ...flatten(load(join(dir, "component.tokens.json"))),
};

function resolve(value, table, seen = new Set()) {
  if (typeof value !== "string") return value;
  return value.replace(/\{([^}]+)\}/g, (_, ref) => {
    if (seen.has(ref)) throw new Error(`circular token reference: ${ref}`);
    if (!(ref in table)) throw new Error(`unknown token reference: ${ref}`);
    return resolve(table[ref], table, new Set([...seen, ref]));
  });
}

const cssValue = (v) => {
  if (Array.isArray(v)) return v.map((x) => (/\s/.test(x) ? `"${x}"` : x)).join(", ");
  if (v && typeof v === "object") return null; // composite tokens (shadows, typography) are skipped
  return String(v);
};
const varName = (path) => "--" + path.replace(/\./g, "-");

function block(selector, table, keys) {
  const lines = [];
  for (const k of keys) {
    const v = cssValue(resolve(table[k], table));
    if (v !== null) lines.push(`  ${varName(k)}: ${v};`);
  }
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

let css = `/* Generated by tools/tokens-to-css.mjs from ${dir.replace(/^.*?(\.specify|tokens)/, "$1")}.\n   Do not edit by hand: regenerate when the design system changes. Theme: ${name}. */\n\n`;
css += block(":root", base, Object.keys(base));

const modesDir = join(dir, "modes");
if (existsSync(modesDir)) {
  for (const f of readdirSync(modesDir).sort()) {
    const mode = f.replace(/\.tokens\.json$/, "");
    const overrides = flatten(load(join(modesDir, f)));
    if (!Object.keys(overrides).length || mode === "light") continue;
    const table = { ...base, ...overrides };
    css += `\n` + block(`:root[data-theme="${mode}"]`, table, Object.keys(overrides));
  }
}

writeFileSync(out, css);
console.log(`wrote ${out} (${Object.keys(base).length} tokens)`);
