#!/usr/bin/env node
// Builds a theme's fonts.css with every font embedded as a data URI.
// Embedding is what lets a deck opened straight from disk (file://) use its fonts in
// Firefox and Safari, which refuse font files loaded from another folder over file://.
//
//   node tools/embed-fonts.mjs <theme-dir>
//
// <theme-dir>/fonts/fonts.json lists the faces: [{ family, file, weight, style, unicodeRange? }]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const themeDir = process.argv[2];
if (!themeDir) {
  console.error("usage: embed-fonts.mjs <theme-dir>");
  process.exit(1);
}
const faces = JSON.parse(readFileSync(join(themeDir, "fonts", "fonts.json"), "utf8"));

let css = "/* Generated by tools/embed-fonts.mjs from fonts/fonts.json. Do not edit by hand. */\n";
for (const f of faces) {
  const data = readFileSync(join(themeDir, "fonts", f.file)).toString("base64");
  css += `@font-face {
  font-family: "${f.family}";
  src: url(data:font/woff2;base64,${data}) format("woff2");
  font-weight: ${f.weight};
  font-style: ${f.style || "normal"};
  font-display: block;${f.unicodeRange ? `\n  unicode-range: ${f.unicodeRange};` : ""}
}
`;
}
writeFileSync(join(themeDir, "fonts.css"), css);
console.log(`wrote ${join(themeDir, "fonts.css")} (${faces.length} faces)`);
